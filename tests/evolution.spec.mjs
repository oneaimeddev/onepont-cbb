async function user() {
 const email=`qa-${randomUUID()}@example.com`, password=randomUUID();
 const {data,error}=await admin.auth.admin.createUser({email,password,email_confirm:true});
 if(error)throw error;
 const id=data.user.id; users.push(id);
 const profile=await admin.from("profiles").insert({id,display_name:"QA DEMO",profession:"Fisioterapia",can_read_audit:true});
 if(profile.error)throw profile.error;
 const client=createClient(localSupabase.url,localSupabase.publishableKey,{auth:{persistSession:false,autoRefreshToken:false}});
 await client.auth.signInWithPassword({email,password});
 return {id,email,password,client};
}
